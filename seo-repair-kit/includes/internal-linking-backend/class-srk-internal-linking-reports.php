/**
 * Internal Linking Reports Engine.
 *
 * Generates report data from Internal Linking database tables.
 */
class SRK_Internal_Linking_Reports {

	/**
	 * Get report data.
	 *
	 * @param string $report_id Report key.
	 * @return array
	 */
	public static function get_report( $report_id ) {
		$report_id = sanitize_key(
			$report_id
		);

		$allowed_reports = array(
			'internal_links',
			'external_links',
			'domains',
			'anchor_text',
			'top_linked_pages',
			'orphan_content',
			'auto_link',
			'url_changer',
		);

		if (
			! in_array(
				$report_id,
				$allowed_reports,
				true
			)
		) {
			return array(
				'title'   => __(
					'No Report',
					'seo-repair-kit'
				),
				'columns' => array(),
				'rows'    => array(),
			);
		}

		$cache_key = 'srk_il_report_' . $report_id;
		$cached    = get_transient(
			$cache_key
		);

		if ( is_array( $cached ) ) {
			return $cached;
		}

		switch ( $report_id ) {
			case 'internal_links':
				$report = self::internal_links();
				break;

			case 'external_links':
				$report = self::external_links();
				break;

			case 'domains':
				$report = self::domains();
				break;	

			case 'anchor_text':
				$report = self::anchor_text();
				break;

			case 'top_linked_pages':
				$report = self::top_linked_pages();
				break;

			case 'orphan_content':
				$report = self::orphan_content();
				break;

			case 'auto_link':
				$report = self::auto_link();
				break;

			case 'url_changer':
				$report = self::url_changer();
				break;

			default:
				$report = array(
					'title'   => __(
						'No Report',
						'seo-repair-kit'
					),
					'columns' => array(),
					'rows'    => array(),
				);
				break;
		}

		set_transient(
			$cache_key,
			$report,
			30
		);

		return $report;
	}

	/**
	 * Internal Links Report.
	 *
	 * Uses the live link snapshot generated by the Content Index.
	 *
	 * @return array<string,mixed>
	 */
	private static function internal_links() {
		global $wpdb;

		$links_table   = SRK_Internal_Linking_DB::get_table_name( 'links' );
		$content_table = SRK_Internal_Linking_DB::get_table_name( 'content_index' );

		if (
			'' === $links_table ||
			'' === $content_table
		) {
			return array(
				'title'   => __( 'Internal Links Report', 'seo-repair-kit' ),
				'columns' => array(),
				'rows'    => array(),
			);
		}

		$rows = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT
					COALESCE(
						NULLIF(source_ci.post_title, ''),
						CONCAT('Post #', l.source_post_id)
					) AS source_page,

					COALESCE(
						source_ci.post_url,
						''
					) AS source_url,

					COALESCE(
						NULLIF(target_ci.post_title, ''),
						l.target_url
					) AS target_page,

					l.target_url AS target_url,

					COALESCE(
						l.anchor_text,
						''
					) AS anchor_text

				FROM %i AS l

				LEFT JOIN %i AS source_ci
					ON source_ci.post_id = l.source_post_id

				LEFT JOIN %i AS target_ci
					ON target_ci.post_id = l.target_post_id

				WHERE l.is_internal = %d

				ORDER BY l.id DESC

				LIMIT %d",
				$links_table,
				$content_table,
				$content_table,
				1,
				1000
			),
			ARRAY_A
		);

		return array(
			'title' => __(
				'Internal Links Report',
				'seo-repair-kit'
			),

			'columns' => array(
				__( 'Source Page', 'seo-repair-kit' ),
				__( 'Source URL', 'seo-repair-kit' ),
				__( 'Target Page', 'seo-repair-kit' ),
				__( 'Target URL', 'seo-repair-kit' ),
				__( 'Anchor Text', 'seo-repair-kit' ),
			),

			'rows' => is_array( $rows )
				? $rows
				: array(),
		);
	}

	/**
	 * External Links Report
	 */
	private static function external_links() {
		global $wpdb;

		$links_table   = SRK_Internal_Linking_DB::get_table_name( 'links' );
		$content_table = SRK_Internal_Linking_DB::get_table_name( 'content_index' );

		if (
			'' === $links_table ||
			'' === $content_table
		) {
			return array(
				'title'   => __( 'External Links Report', 'seo-repair-kit' ),
				'columns' => array(),
				'rows'    => array(),
			);
		}

		$rows = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT
					COALESCE(
						NULLIF(ci.post_title, ''),
						CONCAT('Post #', l.source_post_id)
					) AS source_page,

					COALESCE(
						ci.post_url,
						''
					) AS source_url,

					LOWER(
						REPLACE(
							SUBSTRING_INDEX(
								SUBSTRING_INDEX(
									l.target_url,
									'//',
									-1
								),
								'/',
								1
							),
							'www.',
							''
						)
					) AS domain,

					l.target_url AS external_url,

					COALESCE(
						l.anchor_text,
						''
					) AS anchor_text

				FROM %i AS l

				LEFT JOIN %i AS ci
					ON ci.post_id = l.source_post_id

				WHERE l.is_internal = %d
					AND l.target_url <> ''

				ORDER BY l.id DESC

				LIMIT %d",
				$links_table,
				$content_table,
				0,
				1000
			),
			ARRAY_A
		);

		return array(
			'title' => __(
				'External Links Report',
				'seo-repair-kit'
			),

			'columns' => array(
				__( 'Source Page', 'seo-repair-kit' ),
				__( 'Source URL', 'seo-repair-kit' ),
				__( 'Domain', 'seo-repair-kit' ),
				__( 'External URL', 'seo-repair-kit' ),
				__( 'Anchor Text', 'seo-repair-kit' ),
			),

			'rows' => is_array( $rows )
				? $rows
				: array(),
		);
	}

	/**
	 * Anchor Text Report
	 */
	private static function anchor_text() {

		global $wpdb;

		$table =
		SRK_Internal_Linking_DB::get_table_name('links');

		$rows=$wpdb->get_results(
			"
			SELECT
			anchor_text,
			COUNT(*) AS usage_count

			FROM {$table}

			WHERE anchor_text != ''

			GROUP BY anchor_text

			ORDER BY usage_count DESC

			LIMIT 200
			",
			ARRAY_A
		);

		return array(
			'title'=>'Anchor Text Report',
			'columns'=>array(
				'Anchor Text',
				'Usage'
			),
			'rows'=>$rows
		);


	}

	/**
	 * Domains Report.
	 *
	 * Aggregates indexed external links by normalized hostname.
	 *
	 * @return array<string,mixed>
	 */
	private static function domains() {
		if (
			! class_exists( 'SRK_Internal_Linking_DB' ) ||
			! method_exists(
				'SRK_Internal_Linking_DB',
				'get_domains_report'
			)
		) {
			return array(
				'title'   => __( 'Domains Report', 'seo-repair-kit' ),
				'columns' => array(),
				'rows'    => array(),
			);
		}

		$domains = SRK_Internal_Linking_DB::get_domains_report();

		$rows = array();

		foreach ( (array) $domains as $domain ) {
			$domain_name = sanitize_text_field(
				$domain['domain'] ?? ''
			);

			if ( '' === $domain_name ) {
				continue;
			}

			$rows[] = array(
				'domain'      => $domain_name,
				'posts_count' => absint(
					$domain['posts_count'] ?? 0
				),
				'links_count' => absint(
					$domain['links_count'] ?? 0
				),
			);
		}

		return array(
			'title' => __(
				'Domains Report',
				'seo-repair-kit'
			),

			'columns' => array(
				__( 'Domain', 'seo-repair-kit' ),
				__( 'Posts', 'seo-repair-kit' ),
				__( 'Links', 'seo-repair-kit' ),
			),

			'rows' => $rows,
		);
	}

	/**
	 * Top Linked Pages
	 */
	private static function top_linked_pages(){

		global $wpdb;

		$table =
		SRK_Internal_Linking_DB::get_table_name('content_index');


		$rows=$wpdb->get_results(
			"
			SELECT

			post_title,
			post_url,
			internal_inbound_count,
			internal_outbound_count

			FROM {$table}

			ORDER BY internal_inbound_count DESC

			LIMIT 200
			",
			ARRAY_A
		);


		return array(
			'title'=>'Top Linked Pages',
			'columns'=>array(
				'Title',
				'URL',
				'Inbound Links',
				'Outbound Links'
			),
			'rows'=>$rows
		);


	}

	/**
	 * Orphan Content
	 */
	private static function orphan_content(){

		global $wpdb;

		$table =
		SRK_Internal_Linking_DB::get_table_name('content_index');

		$rows=$wpdb->get_results(
			$wpdb->prepare(
				"
			SELECT

			post_title,
			post_url,
			internal_inbound_count,
			orphan_status

			FROM {$table}

			WHERE orphan_status IN ('critical','low')

			ORDER BY internal_inbound_count ASC

			LIMIT %d
			",
				1000
			),
			ARRAY_A
		);



		return array(
			'title'=>'Orphan Content Report',
			'columns'=>array(
				'Title',
				'URL',
				'Inbound Links',
				'Status'
			),
			'rows'=>$rows
		);


	}

	/**
	 * Auto Linking Report.
	 *
	 * @return array<string,mixed>
	 */
	private static function auto_link() {
		global $wpdb;

		$table = SRK_Internal_Linking_DB::get_table_name(
			'auto_rules'
		);

		$rows = $wpdb->get_results(
			"SELECT
				keyword,
				target_url,
				GREATEST(
					links_created - removed_count,
					0
				) AS active_links,
				removed_count AS removed_links,
				last_scan_at
			FROM {$table}
			ORDER BY id DESC
			LIMIT 200",
			ARRAY_A
		); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		return array(
			'title'   => __(
				'Auto Linking Report',
				'seo-repair-kit'
			),
			'columns' => array(
				__(
					'Keyword',
					'seo-repair-kit'
				),
				__(
					'Target URL',
					'seo-repair-kit'
				),
				__(
					'Active Links',
					'seo-repair-kit'
				),
				__(
					'Removed Links',
					'seo-repair-kit'
				),
				__(
					'Last Scan',
					'seo-repair-kit'
				),
			),
			'rows'    => $rows,
		);
	}

	/**
	 * URL Changer History
	 */
	private static function url_changer(){

		global $wpdb;

		$table =
		SRK_Internal_Linking_DB::get_table_name('url_changes');

		$rows=$wpdb->get_results(
			"
			SELECT

			old_url,
			new_url,
			affected_posts,
			changed_links,
			status,
			created_at

			FROM {$table}

			ORDER BY id DESC

			",
			ARRAY_A
		);



		return array(
			'title'=>'URL Changer History',
			'columns'=>array(
				'Old URL',
				'New URL',
				'Affected Posts',
				'Changed Links',
				'Status',
				'Date'
			),
			'rows'=>$rows
		);


	}

}
