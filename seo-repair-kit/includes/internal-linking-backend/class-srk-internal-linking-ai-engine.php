class SRK_Internal_Linking_AI_Engine {

	const OPENROUTER_CHAT_URL      = 'https://openrouter.ai/api/v1/chat/completions';
	const OPENROUTER_EMBEDDING_URL = 'https://openrouter.ai/api/v1/embeddings';
	const DEFAULT_CHAT_MODEL 	   = 'openrouter/free';
	const DEFAULT_EMBEDDING_MODEL  = 'nvidia/nemotron-3-embed-1b:free';
	const SIMILARITY_THRESHOLD     = 0.65;
	const MAX_SEMANTIC_TARGETS     = 10;
	const EMBEDDING_CHUNK_SIZE 	   = 10000;

	/**
	 * Generate and store embedding for one WordPress post.
	 *
	 * AI reads directly from the live WordPress post.
	 *
	 * @param int $post_id Post ID.
	 * @return array|WP_Error
	 */
	public static function generate_embedding( $post_id ) {
		$post_id = absint( $post_id );

		if ( ! $post_id ) {
			return new WP_Error(
				'srk_ai_invalid_post',
				__(
					'Invalid WordPress post ID.',
					'seo-repair-kit'
				)
			);
		}

		if ( ! self::is_enabled() ) {
			return new WP_Error(
				'srk_ai_disabled',
				__(
					'AI semantic engine is disabled.',
					'seo-repair-kit'
				)
			);
		}

		/*
		* Read the current WordPress content directly.
		*/
		$document = self::get_post_document(
			$post_id
		);

		if ( is_wp_error( $document ) ) {
			return $document;
		}

		$embedding_config =
			SRK_Internal_Linking_AI_Provider::
				resolve_embedding_config();

		if ( is_wp_error( $embedding_config ) ) {
			return $embedding_config;
		}

		$model =
			sanitize_text_field(
				$embedding_config['model']
			);

		$provider =
			sanitize_key(
				$embedding_config['provider']
			);

		$base_url =
			esc_url_raw(
				$embedding_config['base_url']
					?? ''
			);

		/*
		* Provider + endpoint + model identity.
		*
		* This prevents vectors generated by different providers/models
		* from being incorrectly reused or compared.
		*/
		$embedding_profile =
			SRK_Internal_Linking_AI_Provider::get_embedding_profile(
				$model,
				$provider,
				$base_url
			);

		/*
		* Build the exact document representation that will be sent through
		* the embedding pipeline.
		*/
		$text = self::build_embedding_text(
			$document
		);

		if ( '' === trim( $text ) ) {
			return new WP_Error(
				'srk_ai_empty_content',
				__(
					'The WordPress post does not contain enough content for AI processing.',
					'seo-repair-kit'
				)
			);
		}

		/*
		* Hash the exact embedding input.
		*
		* Any meaningful content change automatically causes the vector
		* to be regenerated.
		*/
		$embedding_content_hash = hash(
			'sha256',
			$text
		);

		/*
		* Reuse an existing embedding only when:
		*
		* 1. it completed successfully;
		* 2. the exact embedding input is unchanged;
		* 3. provider, endpoint and model are unchanged.
		*/
		$existing =
			SRK_Internal_Linking_DB::get_embedding_by_post_id(
				$post_id
			);

		if (
			$existing &&
			'ready' === ( $existing['status'] ?? '' ) &&
			! empty( $existing['content_hash'] ) &&
			hash_equals(
				(string) $existing['content_hash'],
				(string) $embedding_content_hash
			) &&
			hash_equals(
				(string) ( $existing['model'] ?? '' ),
				(string) $embedding_profile
			)
		) {
			return array(
				'post_id' => $post_id,
				'cached'  => true,
			);
		}

		/*
		* Generate the document embedding once.
		*
		* request_document_embedding() handles long-content chunking
		* internally, so the complete post content is preserved.
		*/
		$vector =
			self::request_document_embedding(
				$text,
				$model,
				$provider,
				$base_url
			);

		/*
		* API/provider failure.
		*/
		if ( is_wp_error( $vector ) ) {
			$failed_embedding_id =
				SRK_Internal_Linking_DB::upsert_embedding(
					array(
						'post_id'        => $post_id,
						'embedding_json' => '[]',
						'content_hash'   => $embedding_content_hash,
						'model'          => $embedding_profile,
						'status'         => 'failed',
					)
				);

			if ( is_wp_error( $failed_embedding_id ) ) {
				return $failed_embedding_id;
			}

			delete_transient(
				'srk_il_ai_status'
			);

			return $vector;
		}

		/*
		* Provider returned no usable vector.
		*/
		if (
			empty( $vector ) ||
			! is_array( $vector )
		) {
			return new WP_Error(
				'srk_ai_empty_embedding',
				__(
					'Embedding provider returned an empty vector.',
					'seo-repair-kit'
				)
			);
		}

		/*
		* Store the successfully generated embedding.
		*/
		$embedding_id =
			SRK_Internal_Linking_DB::upsert_embedding(
				array(
					'post_id'        => $post_id,
					'embedding_json' => wp_json_encode(
						$vector
					),
					'content_hash'   => $embedding_content_hash,
					'model'          => $embedding_profile,
					'status'         => 'ready',
				)
			);

		if ( is_wp_error( $embedding_id ) ) {
			return $embedding_id;
		}

		if ( ! $embedding_id ) {
			return new WP_Error(
				'srk_ai_embedding_not_stored',
				__(
					'Embedding was generated but could not be stored in the database.',
					'seo-repair-kit'
				)
			);
		}

		delete_transient(
			'srk_il_ai_status'
		);

		return array(
			'post_id'      => $post_id,
			'embedding_id' => absint( $embedding_id ),
			'cached'       => false,
		);
	}
	/**
	 * AI gatekeeper: return approved target map or null for full fallback.
	 *
	 * null  = AI disabled, unavailable, or source embedding missing → all targets allowed.
	 * array = AI-active map of target_post_id => cosine similarity (may be empty).
	 *
	 * @param int $source_post_id Source post ID.
	 * @return array|null
	 */
	public static function get_approved_targets( $source_post_id, $scan_run_id = 0 ) {
		$source_post_id = absint( $source_post_id );
		$scan_run_id    = absint( $scan_run_id );

		if (
			! self::is_enabled() ||
			! self::semantic_matching_enabled()
		) {
			return null;
		}

		$source_embedding =
			SRK_Internal_Linking_DB::get_embedding_by_post_id(
				$source_post_id
			);

		if (
			! $source_embedding ||
			'ready' !== ( $source_embedding['status'] ?? '' )
		) {
			return null;
		}

		$cache_key = 'srk_il_ai_filter_' . $source_post_id;

		/*
		* Full scan runs must recompute staging rows so each candidate receives
		* the correct scan_run_id.
		*/
		if ( ! $scan_run_id ) {
			$cached = get_transient( $cache_key );

			if ( is_array( $cached ) ) {
				return $cached;
			}
		}

		$source_vector = json_decode(
			$source_embedding['embedding_json'] ?? '[]',
			true
		);

		if (
			! is_array( $source_vector ) ||
			empty( $source_vector )
		) {
			return null;
		}

		$approved = self::compute_approved_targets(
			$source_post_id,
			$source_vector,
			$scan_run_id
		);

		set_transient(
			$cache_key,
			$approved,
			HOUR_IN_SECONDS
		);

		return $approved;
	}

	/**
	 * Compute and persist AI-approved target posts for a source.
	 *
	 * @param int   $source_post_id Source post ID.
	 * @param array $source_vector  Source embedding vector.
	 * @return array<int,float> target_post_id => similarity.
	 */
	private static function compute_approved_targets( $source_post_id, $source_vector, $scan_run_id = 0 ) {
		$approved       = array();
		$used_sentences = array();
		$matches        = array();
		$scan_run_id    = absint( $scan_run_id );

		$source_embedding =
			SRK_Internal_Linking_DB::get_embedding_by_post_id(
				$source_post_id
			);

		if (
			! $source_embedding ||
			'ready' !== ( $source_embedding['status'] ?? '' )
		) {
			return array();
		}

		$source_model = sanitize_text_field(
			$source_embedding['model'] ?? ''
		);

		/*
		* Process every embedding through pagination. No 500-post truncation.
		*/
		$batch_size = 200;
		$offset     = 0;

		do {
			$batch = SRK_Internal_Linking_DB::get_embeddings_batch(
				$batch_size,
				$offset
			);

			foreach ( $batch as $target_embedding ) {
				$target_id = absint(
					$target_embedding['post_id']
				);

				if (
					$target_id === $source_post_id ||
					'ready' !== (
						$target_embedding['status'] ?? ''
					)
				) {
					continue;
				}

				if (
					'' === $source_model ||
					$source_model !== sanitize_text_field(
						$target_embedding['model'] ?? ''
					)
				) {
					continue;
				}

				if (
					SRK_Internal_Linking_DB::source_has_active_link_to_target(
						$source_post_id,
						$target_id
					)
				) {
					continue;
				}

				$target_vector = json_decode(
					$target_embedding['embedding_json'] ?? '[]',
					true
				);

				if (
					! is_array( $target_vector ) ||
					empty( $target_vector )
				) {
					continue;
				}

				$similarity = self::cosine_similarity(
					$source_vector,
					$target_vector
				);

				if (
					$similarity <
					self::SIMILARITY_THRESHOLD
				) {
					continue;
				}

				$matches[] = array(
					'target_post_id'   => $target_id,
					'similarity_score' => $similarity,
				);
			}

			$offset += $batch_size;
		} while ( count( $batch ) === $batch_size );

		usort(
			$matches,
			static function ( $first, $second ) {
				return (
					$second['similarity_score']
					<=>
					$first['similarity_score']
				);
			}
		);

		$matches = array_slice(
			$matches,
			0,
			self::MAX_SEMANTIC_TARGETS
		);

		$source_row =
			self::get_post_document(
				$source_post_id
			);

		if ( is_wp_error( $source_row ) ) {
			return array();
		}

		foreach ( $matches as $match ) {
			$target_id = absint(
				$match['target_post_id']
			);

			$similarity = floatval(
				$match['similarity_score']
			);

			$target_row =
				self::get_post_document(
					$target_id
				);

			if ( is_wp_error( $target_row ) ) {
				continue;
			}

			if ( ! $source_row || ! $target_row ) {
				continue;
			}

			$anchor_data =	self::suggest_semantic_anchor(
				$source_row,
				$target_row,
				$source_post_id
			);

			if ( empty( $anchor_data['anchor'] ) ) {
				continue;
			}

			if ( ! empty( $anchor_data['sentence'] ) ) {
				$sentence_key = md5(
					strtolower(
						trim(
							$anchor_data['sentence']
						)
					)
				);

				if (
					isset(
						$used_sentences[ $sentence_key ]
					)
				) {
					continue;
				}

				$used_sentences[ $sentence_key ] = true;
			}

			if (
				self::anchor_already_used(
					$source_post_id,
					$anchor_data['anchor']
				)
			) {
				continue;
			}

			$ai_score = min(
				100,
				max(
					0,
					absint(
						round(
							$similarity * 100
						)
					)
				)
			);

			$reason = sprintf(
				/* translators: %s: semantic similarity percentage */
				__(
					'AI semantic similarity: %s. Anchor selected through local phrase matching.',
					'seo-repair-kit'
				),
				number_format_i18n(
					$similarity * 100,
					1
				) . '%'
			);

			$opportunity_id =
				SRK_Internal_Linking_Opportunities::create_from_ai_candidate(
					array(
						'scan_run_id'    => $scan_run_id ?: null,
						'source_post_id' => $source_post_id,
						'target_post_id' => $target_id,

						'anchor_text' =>
							$anchor_data['anchor'],

						'sentence' =>
							$anchor_data['sentence'],

						'reason' =>
							$reason,

						'ai_score' =>
							$ai_score,

						'ai_similarity' =>
							$similarity,
							
						'status' => $scan_run_id
							? 'building'
							: 'pending',
					)
				);

			if ( $opportunity_id ) {
				$approved[ $target_id ] =
					$similarity;
			}
		}

		return $approved;
	}

	/**
	 * Cache AI gatekeeper approvals for a source post (background batch step).
	 *
	 * @param int $source_post_id Source post ID.
	 * @return array
	 */
	public static function cache_approved_targets_for_post( $source_post_id, $scan_run_id = 0 ) {
		$source_post_id = absint( $source_post_id );
		$scan_run_id    = absint( $scan_run_id );

		if (
			! self::is_enabled() ||
			! self::semantic_matching_enabled()
		) {
			return array(
				'approved' => 0,
			);
		}

		delete_transient(
			'srk_il_ai_filter_' . $source_post_id
		);

		$map = self::get_approved_targets(
			$source_post_id,
			$scan_run_id
		);

		return array(
			'approved' => is_array( $map )
				? count( $map )
				: 0,
		);
	}

	/**
	 * Find semantic relationships for a source post using stored embeddings.
	 *
	 * @param int $source_post_id Source post ID.
	 * @return array
	 */
	public static function generate_semantic_links_for_post( $source_post_id, $scan_run_id = 0 ) {
		$result = self::cache_approved_targets_for_post(
			$source_post_id,
			$scan_run_id
		);

		delete_transient( 'srk_il_ai_status' );

		return array(
			'created' => absint(
				$result['approved'] ?? 0
			),
		);
	}

	/**
	 * Build semantic graph for a batch of posts.
	 *
	 * @param int $limit  Batch size.
	 * @param int $offset Offset.
	 * @return array
	 */
	public static function generate_semantic_graph_batch( $limit = 5, $offset = 0, $scan_run_id = 0 ) {
		$rows = SRK_Internal_Linking_DB::get_embeddings_batch(
			$limit,
			$offset
		);

		$created = 0;

		foreach ( $rows as $row ) {

			$post_id = absint(
				$row['post_id']
			);

			if ( ! $post_id ) {
				continue;
			}

			$result =
				self::generate_semantic_links_for_post(
					$post_id,
					absint(
						$scan_run_id
					)
				);

			$created += absint(
				$result['created'] ?? 0
			);

			/*
			* Rule + AI selection for this source is now complete.
			*/
			SRK_Internal_Linking_DB::
			finalize_building_opportunities(
				absint(
					$scan_run_id
				),
				$post_id
			);
		}

		return array(
			'processed' => count( $rows ),
			'created'   => $created,
			'complete'  => count( $rows ) < $limit,
		);
	}

