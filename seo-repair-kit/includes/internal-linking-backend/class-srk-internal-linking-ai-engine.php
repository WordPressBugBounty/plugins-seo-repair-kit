	/**
	 * Determine whether the AI engine is operational.
	 *
	 * AI requires:
	 * - the global Internal Linking module;
	 * - AI enabled;
	 * - a stored API key.
	 *
	 * @return bool
	 */
	public static function is_enabled() {
		$settings = SRK_Internal_Linking_Settings::get();

		$internal_linking_enabled = method_exists(
			'SRK_Internal_Linking_Settings',
			'is_enabled'
		)
			? SRK_Internal_Linking_Settings::is_enabled()
			: ! empty( $settings['enabled'] );

		return (
			$internal_linking_enabled &&
			! empty( $settings['ai_enabled'] ) &&
			class_exists(
				'SRK_Internal_Linking_AI_Provider'
			) &&
			SRK_Internal_Linking_AI_Provider::is_configured()
		);
	}

