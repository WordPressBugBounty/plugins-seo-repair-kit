		}



		return $anchor;

	}

	/**
	 * Find original phrase inside sentence.
	 *
	 * @param string $sentence Sentence text.
	 * @param string $phrase   Phrase to locate.
	 * @return string
	 */
	private static function find_original_phrase( $sentence, $phrase ) {
		$pattern = '/' . preg_quote( $phrase, '/' ) . '/iu';

		if ( preg_match( $pattern, $sentence, $matches ) ) {
			return trim( $matches[0] );
		}

		return '';
	}

	/**
	 * Parse JSON from AI response text.
	 *
	 * @param string $text Raw AI response.
	 * @return array
	 */
	private static function parse_json_response( $text ) {
		$text = trim( (string) $text );

		if ( preg_match( '/\{.*\}/s', $text, $matches ) ) {
			$decoded = json_decode( $matches[0], true );

			if ( is_array( $decoded ) ) {
				return $decoded;
			}
		}

		return array();
	}

	/**
	 * Calculate cosine similarity between compatible vectors.
	 *
	 * @param array $a Vector A.
	 * @param array $b Vector B.
	 * @return float
	 */
	public static function cosine_similarity( $a, $b ) {
		$a = array_values(
			array_map(
				'floatval',
				(array) $a
			)
		);

		$b = array_values(
			array_map(
				'floatval',
				(array) $b
			)
		);

		if (
			empty( $a ) ||
			empty( $b ) ||
			count( $a ) !== count( $b )
		) {
			return 0.0;
		}

		$dot   = 0.0;
		$norma = 0.0;
		$normb = 0.0;
		$len   = count( $a );

		for ( $i = 0; $i < $len; $i++ ) {
			if (
				! is_finite( $a[ $i ] ) ||
				! is_finite( $b[ $i ] )
			) {
				return 0.0;
			}

			$dot   += $a[ $i ] * $b[ $i ];
			$norma += $a[ $i ] * $a[ $i ];
			$normb += $b[ $i ] * $b[ $i ];
		}

		if ( $norma <= 0.0 || $normb <= 0.0 ) {
			return 0.0;
		}

		$similarity = $dot / (
			sqrt( $norma ) *
			sqrt( $normb )
		);

		return max(
			-1.0,
			min( 1.0, $similarity )
		);
	}

	/**
	 * Local fallback embedding when API is unavailable.
	 *
	 * @param string $text Input text.
	 * @return array
	 */
	private static function fallback_embedding( $text ) {
		$words = SRK_Internal_Linking_Keywords::meaningful_words( $text );
		$vector = array_fill( 0, 128, 0.0 );

		foreach ( $words as $word ) {
			$index = abs( crc32( $word ) ) % 128;
			$vector[ $index ] += 1.0;
		}

		$max = max( $vector );

		if ( $max > 0 ) {
			foreach ( $vector as $i => $value ) {
				$vector[ $i ] = $value / $max;
			}
		}

		return $vector;
	}

	/**
	 * Build AI document directly from WordPress post data.
	 *
	 * AI must not depend on the Internal Linking Content Index.
	 *
	 * @param int $post_id WordPress post ID.
	 * @return array|WP_Error
	 */
	private static function get_post_document( $post_id ) {
		$post_id = absint(
			$post_id
		);

		$post = get_post(
			$post_id
		);

		if ( ! $post ) {
			return new WP_Error(
				'srk_ai_post_missing',
				__(
					'WordPress post could not be found.',
					'seo-repair-kit'
				)
			);
		}

		if ( 'publish' !== $post->post_status ) {
			return new WP_Error(
				'srk_ai_post_not_published',
				__(
					'Only published content can be processed by the AI engine.',
					'seo-repair-kit'
				)
			);
		}

		$settings =
			SRK_Internal_Linking_Settings::get();

		$allowed_post_types =
			! empty( $settings['post_types'] )
				? array_values(
					array_filter(
						array_map(
							'sanitize_key',
							(array) $settings['post_types']
						)
					)
				)
				: array(
					'post',
					'page',
				);

		if (
			! empty( $allowed_post_types ) &&
			! in_array(
				$post->post_type,
				$allowed_post_types,
				true
			)
		) {
			return new WP_Error(
				'srk_ai_post_type_not_allowed',
				__(
					'This post type is excluded from Internal Linking.',
					'seo-repair-kit'
				)
			);
		}

		$raw_content =
			(string) $post->post_content;

		$content_hash = hash(
			'sha256',
			(string) $post->post_title .
			'|' .
			$raw_content
		);

		/*
		* Elementor documents keep their real editable content outside
		* normal WordPress post_content.
		*/
		if (
			class_exists(
				'SRK_Internal_Linking_Elementor'
			) &&
			SRK_Internal_Linking_Elementor::
				is_elementor_post(
					$post_id
				)
		) {
			$elementor_content =
				SRK_Internal_Linking_Elementor::
					get_analysis_content(
						$post_id,
						true
					);

			if (
				'' !== trim(
					$elementor_content
				)
			) {
				$raw_content =
					$elementor_content;

				/*
				* Keep AI, Indexer and queue content identity aligned.
				*/
				$content_hash =
					SRK_Internal_Linking_Elementor::
						get_content_hash(
							$post_id
						);
			}
		}

		/*
		* Reuse the rule engine's canonical content-normalization pipeline.
		* Do not maintain a second copy of stripping/decoding logic here.
		*/
		$content =
			SRK_Internal_Linking_Indexer::plain_text(
				SRK_Internal_Linking_Indexer::clean_content(
					$raw_content
				)
			);

		return array(
			'post_id'       => $post_id,
			'post_type'     => $post->post_type,
			'post_status'   => $post->post_status,
			'post_title'    => $post->post_title,
			'post_content'  => $raw_content,
			'plain_content' => $content,
			'post_url'      => get_permalink(
				$post_id
			),
			'content_hash'  => $content_hash,
		);
	}

	private static function anchor_already_used( $source_post_id, $anchor ) {

		if (
			! $source_post_id ||
			'' === trim(
				(string) $anchor
			)
		) {
			return false;
		}

		return SRK_Internal_Linking_DB::
			ai_opportunity_anchor_exists(
				absint(
					$source_post_id
				),
				sanitize_text_field(
					$anchor
				)
			);
	}
	
		/**
	 * Extract contiguous anchor phrases from a sentence.
	 *
	 * Uses the existing Internal Linking anchor-length settings instead of
	 * maintaining separate AI-only limits.
	 *
	 * @param string $sentence Source sentence.
	 * @return array<int,string>
	 */
	private static function extract_anchor_candidates( $sentence ) {
		$settings =
			SRK_Internal_Linking_Settings::get();

		$min_words =
		! empty( $settings['min_anchor_words'] )
			? min(
				9,
				max(
					2,
					absint(
						$settings['min_anchor_words']
					)
				)
			)
			: 2;

	$max_words =
		! empty( $settings['max_anchor_words'] )
			? min(
				9,
				max(
					$min_words,
					absint(
						$settings['max_anchor_words']
					)
				)
			)
			: 9;

		$words = preg_split(
			'/\s+/u',
			trim(
				wp_strip_all_tags(
					(string) $sentence
				)
			),
			-1,
			PREG_SPLIT_NO_EMPTY
		);

		if (
			! is_array( $words ) ||
			empty( $words )
		) {
			return array();
		}

		$candidates = array();
		$count      = count( $words );

		for (
			$start = 0;
			$start < $count;
			$start++
		) {
			for (
				$length = $min_words;
				$length <= $max_words;
				$length++
			) {
				if (
					$start + $length >
					$count
				) {
					break;
				}

				$phrase = trim(
					implode(
						' ',
						array_slice(
							$words,
							$start,
							$length
						)
					)
				);

				if (
					'' === $phrase ||
					strlen( $phrase ) < 6
				) {
					continue;
				}

				$candidates[] =
					$phrase;
			}
		}

		return array_values(
			array_unique(
				$candidates
			)
		);
	}
	
