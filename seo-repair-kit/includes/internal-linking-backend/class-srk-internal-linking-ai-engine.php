	/**
	 * Build embedding input from live WordPress post data.
	 *
	 * @param array $document AI post document.
	 * @return string
	 */
	private static function build_embedding_text( $document ) {
		$parts = array(
			trim(
				(string) (
					$document['post_title'] ?? ''
				)
			),
			trim(
				(string) (
					$document['plain_content'] ?? ''
				)
			),
		);

		$parts = array_values(
			array_filter(
				$parts,
				static function ( $part ) {
					return '' !== $part;
				}
			)
		);

		return trim(
			implode(
				"\n\n",
				$parts
			)
		);
	}

	/**
	 * Generate one embedding vector using the complete document.
	 *
	 * Long documents are divided into provider-safe requests. Every chunk
	 * contributes to the final weighted vector, so no document content is
	 * discarded because of a fixed character limit.
	 *
	 * @param string $text  Complete embedding input.
	 * @param string $model Embedding model.
	 * @return array|WP_Error
	 */
	private static function request_document_embedding( $text, $model, $provider, $base_url ) {
		$chunks =
			self::split_embedding_text(
				$text
			);

		if ( empty( $chunks ) ) {

			return new WP_Error(
				'srk_ai_empty_embedding_input',
				__(
					'Embedding input cannot be empty.',
					'seo-repair-kit'
				)
			);
		}

		/*
		* Normal-sized content requires only one API call.
		*/
		if ( 1 === count( $chunks ) ) {

			return self::request_embedding(
				$chunks[0],
				$model,
				$provider,
				$base_url
			);
		}

		$vectors = array();
		$weights = array();

		foreach ( $chunks as $chunk ) {

			$vector =
				self::request_embedding(
					$chunk,
					$model,
					$provider,
					$base_url
				);

			if ( is_wp_error( $vector ) ) {
				return $vector;
			}

			if (
				empty( $vector ) ||
				! is_array( $vector )
			) {
				return new WP_Error(
					'srk_ai_invalid_chunk_embedding',
					__(
						'Embedding provider returned an invalid chunk vector.',
						'seo-repair-kit'
					)
				);
			}

			$vectors[] =
				array_values(
					array_map(
						'floatval',
						$vector
					)
				);

			$weights[] =
				max(
					1,
					strlen( $chunk )
				);
		}

		return self::average_embedding_vectors(
			$vectors,
			$weights
		);
	}

	/**
	 * Split complete document text into provider-safe embedding requests.
	 *
	 * This method does not impose a total document limit.
	 *
	 * @param string $text Complete embedding input.
	 * @return array<int,string>
	 */
	private static function split_embedding_text( $text ) {
		$text = trim(
			(string) $text
		);

		if ( '' === $text ) {
			return array();
		}

		if (
			strlen( $text ) <=
			self::EMBEDDING_CHUNK_SIZE
		) {
			return array(
				$text,
			);
		}

		$words = preg_split(
			'/\s+/u',
			$text,
			-1,
			PREG_SPLIT_NO_EMPTY
		);

		if (
			! is_array( $words ) ||
			empty( $words )
		) {
			return array(
				$text,
			);
		}

		$chunks  = array();
		$current = '';

		foreach ( $words as $word ) {
			$candidate =
				'' === $current
					? $word
					: $current . ' ' . $word;

			if (
				'' !== $current &&
				strlen( $candidate ) >
					self::EMBEDDING_CHUNK_SIZE
			) {
				$chunks[] = $current;
				$current  = $word;

				continue;
			}

			$current = $candidate;
		}

		if ( '' !== $current ) {
			$chunks[] = $current;
		}

		return $chunks;
	}

	/**
	 * Combine multiple chunk vectors into one weighted document vector.
	 *
	 * @param array<int,array<int,float>> $vectors Chunk embedding vectors.
	 * @param array<int,int>              $weights Relative chunk weights.
	 * @return array|WP_Error
	 */
	private static function average_embedding_vectors(
		$vectors,
		$weights
	) {
		if ( empty( $vectors ) ) {
			return new WP_Error(
				'srk_ai_no_chunk_vectors',
				__(
					'No embedding vectors were generated.',
					'seo-repair-kit'
				)
			);
		}

		$first = reset(
			$vectors
		);

		if (
			! is_array( $first ) ||
			empty( $first )
		) {
			return new WP_Error(
				'srk_ai_invalid_chunk_dimensions',
				__(
					'Embedding chunk dimensions are invalid.',
					'seo-repair-kit'
				)
			);
		}

		$dimensions = count(
			$first
		);

		$combined = array_fill(
			0,
			$dimensions,
			0.0
		);

		$total_weight = 0.0;

		foreach (
			array_values( $vectors )
			as $index => $vector
		) {
			$vector = array_values(
				array_map(
					'floatval',
					(array) $vector
				)
			);

			if (
				count( $vector ) !==
				$dimensions
			) {
				return new WP_Error(
					'srk_ai_chunk_dimension_mismatch',
					__(
						'Embedding provider returned inconsistent vector dimensions.',
						'seo-repair-kit'
					)
				);
			}

			$weight = max(
				1.0,
				(float) (
					$weights[ $index ] ?? 1
				)
			);

			$total_weight += $weight;

			for (
				$i = 0;
				$i < $dimensions;
				$i++
			) {
				if (
					! is_finite(
						$vector[ $i ]
					)
				) {
					return new WP_Error(
						'srk_ai_invalid_chunk_value',
						__(
							'Embedding provider returned an invalid vector value.',
							'seo-repair-kit'
						)
					);
				}

				$combined[ $i ] +=
					$vector[ $i ] *
					$weight;
			}
		}

		if ( $total_weight <= 0.0 ) {
			return new WP_Error(
				'srk_ai_invalid_chunk_weight',
				__(
					'Embedding chunk weight is invalid.',
					'seo-repair-kit'
				)
			);
		}

		for (
			$i = 0;
			$i < $dimensions;
			$i++
		) {
			$combined[ $i ] =
				$combined[ $i ] /
				$total_weight;
		}

		return $combined;
	}

	/**
	 * Generate semantic anchor from source content for target page.
	 *
	 * @param array|null $source_row Source indexed content.
	 * @param array|null $target_row Target indexed content.
	 *
	 * @return array
	 */
	private static function suggest_semantic_anchor( $source_row, $target_row, $source_post_id = 0 ) {
		$source_post_id = absint(
			$source_post_id
		);

		$source_content = trim(
			(string) (
				$source_row['plain_content'] ?? ''
			)
		);

		$target_title = trim(
			(string) (
				$target_row['post_title'] ?? ''
			)
		);

		$target_content = trim(
			(string) (
				$target_row['plain_content'] ?? ''
			)
		);

		if (
			'' === $source_content ||
			'' === $target_title
		) {
			return array(
				'anchor'   => '',
				'sentence' => '',
			);
		}

		$sentences =
			SRK_Internal_Linking_Indexer::split_sentences(
				$source_content
			);

		if ( empty( $sentences ) ) {
			return array(
				'anchor'   => '',
				'sentence' => '',
			);
		}

		$title_words =
			SRK_Internal_Linking_Keywords::meaningful_words(
				$target_title
			);

		$content_words =
			SRK_Internal_Linking_Keywords::meaningful_words(
				$target_content
			);

		$title_lookup = array_fill_keys(
			$title_words,
			true
		);

		$content_lookup = array_fill_keys(
			$content_words,
			true
		);

		$candidates = array();

		foreach ( $sentences as $sentence ) {
			$phrases =
				self::extract_anchor_candidates(
					$sentence
				);

			foreach ( $phrases as $phrase ) {
				$phrase_words =
					SRK_Internal_Linking_Keywords::meaningful_words(
						$phrase
					);

				if ( empty( $phrase_words ) ) {
					continue;
				}

				$title_hits   = 0;
				$content_hits = 0;

				foreach ( $phrase_words as $word ) {
					if (
						isset(
							$title_lookup[ $word ]
						)
					) {
						$title_hits++;
					}

					if (
						isset(
							$content_lookup[ $word ]
						)
					) {
						$content_hits++;
					}
				}

				/*
				* A direct target-title term is strong evidence.
				*
				* Otherwise require at least two meaningful terms that
				* occur in the target body. This removes the old
				* title-only gate without accepting arbitrary phrases.
				*/
				if (
					0 === $title_hits &&
					$content_hits < 2
				) {
					continue;
				}

				$candidates[] = array(
					'anchor' =>
						$phrase,

					'sentence' =>
						$sentence,

					/*
					* Prefer target-title identity while still allowing
					* target-body semantic vocabulary.
					*/
					'score' =>
						( $title_hits * 4 ) +
						$content_hits,

					'word_count' =>
						count(
							$phrase_words
						),
				);
			}
		}

		if ( empty( $candidates ) ) {
			return array(
				'anchor'   => '',
				'sentence' => '',
			);
		}

		usort(
			$candidates,
			static function ( $first, $second ) {
				$score_compare =
					absint(
						$second['score'] ?? 0
					)
					<=>
					absint(
						$first['score'] ?? 0
					);

				if ( 0 !== $score_compare ) {
					return $score_compare;
				}

				/*
				* When relevance is equal, prefer the shorter,
				* more natural anchor.
				*/
				return absint(
					$first['word_count'] ?? 0
				)
					<=>
					absint(
						$second['word_count'] ?? 0
					);
			}
		);

		foreach ( $candidates as $candidate ) {
			$anchor = sanitize_text_field(
				$candidate['anchor'] ?? ''
			);

			if ( '' === trim( $anchor ) ) {
				continue;
			}

			if (
				self::anchor_already_used(
					$source_post_id,
					$anchor
				)
			) {
				continue;
			}

			/*
			* Reuse the canonical opportunity engine's eligibility rules.
			*/
			if (
				! SRK_Internal_Linking_Opportunities::
					is_candidate_anchor_eligible(
						$source_post_id,
						$anchor
					)
			) {
				continue;
			}

			return array(
				'anchor' =>
					$anchor,

				'sentence' =>
					wp_html_excerpt(
						$candidate['sentence'],
						220,
						'…'
					),
			);
		}

		return array(
			'anchor'   => '',
			'sentence' => '',
		);
	}

	/**
	 * Use GPT to extract semantic anchor.
	 */
	private static function extract_semantic_anchor_with_gpt(
		$source_content,
		$target_title
	){

		$prompt = "
	You are an SEO internal linking expert.

	Target page:
	{$target_title}

	Source content:
	{$source_content}

	Find ONE natural anchor phrase from the source content that best represents the target page.

	Rules:
	- Phrase must already exist in source content.
	- Do not invent words.
	- Return only anchor text.
	";


		$response =
			self::chat_completion(
				$prompt,
				self::DEFAULT_CHAT_MODEL
			);



		if(
